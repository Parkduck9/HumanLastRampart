const fs=require('fs');
const path=require('path');
const {pathToFileURL}=require('url');
const {chromium}=require('C:/Users/User/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
(async()=>{
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
const url=pathToFileURL(path.resolve(__dirname,'../../../_HTML/6_그림_화면/codex_K-129_우두머리동작_v1.html')).href;
await page.goto(url);await page.waitForFunction(()=>window.assetsReady);
await page.evaluate(()=>window.ready);
const before=await page.locator('body').getAttribute('data-tick');
await page.waitForFunction(v=>Number(document.body.dataset.tick)>Number(v)+2,before);
const motionCount=await page.locator('section[data-motion]').count();
await page.locator('section[data-motion]').first().scrollIntoViewIfNeeded();
await page.screenshot({path:path.join(__dirname,'review_desktop.png')});
await page.locator('#play').click();
await page.locator('#step').click();
const stepOK=await page.locator('section[data-motion]').evaluateAll(xs=>xs.every(x=>x.dataset.frame==='1'));
await page.locator('#mode').selectOption('night');
await page.locator('section[data-motion="wallhand_climb_front"]').scrollIntoViewIfNeeded();
await page.screenshot({path:path.join(__dirname,'review_climb_night.png')});
await page.locator('#mode').selectOption('normal');
await page.locator('#mode').selectOption('lit');
await page.locator('#mode').selectOption('silhouette');
await page.locator('#mode').selectOption('color');
await page.locator('#zoom').selectOption('2');
const zoomOK=await page.locator('.boss').first().evaluate(x=>x.getBoundingClientRect().width===512);
await page.locator('#zoom').selectOption('1');
for(let i=0;i<8;i++)await page.locator('#step').click();
const finalFrames=await page.locator('section[data-motion]').evaluateAll(xs=>xs.map(x=>({motion:x.dataset.motion,frame:Number(x.dataset.frame)})));
await page.locator('section[data-motion="wallhand_death_side"]').scrollIntoViewIfNeeded();
await page.screenshot({path:path.join(__dirname,'review_death.png')});
await page.locator('details').evaluateAll(xs=>xs.forEach(x=>x.open=true));
const allImages=await page.locator('img').evaluateAll(xs=>Promise.all(xs.map(x=>x.decode())).then(()=>xs.every(x=>x.complete&&x.naturalWidth>0&&x.src.startsWith('data:'))));
await page.setViewportSize({width:390,height:844});
await page.evaluate(()=>window.scrollTo(0,0));
await page.screenshot({path:path.join(__dirname,'review_mobile.png')});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
const report={url_scheme:'file',motion_sections:motionCount,animation_advanced:true,step_all_motions:stepOK,all_images_decoded:allImages,zoom_2x:zoomOK,modes_checked:['기본 색','밤의 광선','검은 실루엣','노멀 방향','노멀 조명'],mobile_page_overflow:overflow,final_frames:finalFrames,script_errors:errors};
fs.writeFileSync(path.join(__dirname,'review_validation.json'),JSON.stringify(report,null,2));
await browser.close();console.log(JSON.stringify(report));
if(motionCount!==17||!stepOK||!allImages||!zoomOK||overflow||errors.length)process.exitCode=1;
})().catch(e=>{console.error(e);process.exitCode=1});
